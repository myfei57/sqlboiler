const baselineSQLiteDDL = `
CREATE TABLE pilots (
    id INTEGER PRIMARY KEY,
    name TEXT NOT NULL,
    age BIGINT
);
CREATE TABLE jets (
    id INTEGER PRIMARY KEY,
    pilot_id INTEGER NOT NULL,
    color TEXT,
    FOREIGN KEY (pilot_id) REFERENCES pilots(id)
);
CREATE VIEW pilot_names AS SELECT id, name FROM pilots;
CREATE TABLE gen_demo (
    id INTEGER PRIMARY KEY,
    val INTEGER,
    doubled INTEGER GENERATED ALWAYS AS (val * 2) VIRTUAL
);
`

func newSQLiteDB(t *testing.T, ddl string) string {
	t.Helper()
	dir := t.TempDir()
	path := filepath.Join(dir, "contract.db")

	db, err := sql.Open("sqlite", path)
	require.NoError(t, err)
	_, err = db.Exec(ddl)
	require.NoError(t, err)
	require.NoError(t, db.Close())
	return path
}

func generateModels(t *testing.T, dbPath string) (*boilingcore.State, string) {
	t.Helper()
	out := t.TempDir()
	cfg := &boilingcore.Config{
		DriverName:   "sqlite3",
		PkgName:      "models",
		OutFolder:    out,
		NoTests:      true,
		DriverConfig: drivers.Config{"dbname": dbPath},
		Imports:      importers.NewDefaultImports(),
	}
	state, err := boilingcore.New(cfg)
	require.NoError(t, err)
	require.NoError(t, state.Run())
	return state, out
}

func findTable(t *testing.T, m *schemacontract.Manifest, schema, name string) *schemacontract.TableContract {
	t.Helper()
	for i := range m.Tables {
		if m.Tables[i].SchemaName == schema && m.Tables[i].Name == name {
			return &m.Tables[i]
		}
	}
	t.Fatalf("table %s.%s not found", schema, name)
	return nil
}

func findDiff(t *testing.T, r *schemacontract.Report, pathPart, kind string) *schemacontract.Difference {
	t.Helper()
	for i := range r.Differences {
		d := &r.Differences[i]
		if d.Kind == kind && (pathPart == "" || strings.Contains(d.Path, pathPart)) {
			return d
		}
	}
	return nil
}

// TestSQLiteEndToEndGenerationAndManifest drives the full pipeline: real
// sqlite introspection, real template generation, manifest export and
// compatibility checks against altered databases.
func TestSQLiteEndToEndGenerationAndManifest(t *testing.T) {
	dbPath := newSQLiteDB(t, baselineSQLiteDDL)
	state, out := generateModels(t, dbPath)

	manifest, err := state.SchemaContractManifest()
	require.NoError(t, err)
	require.Equal(t, "sqlite3", manifest.DriverName)

	encoded, err := schemacontract.EncodeManifest(manifest)
	require.NoError(t, err)

	// Determinism: repeated encoding and a fresh generation run must produce
	// the exact same artifact.
	encodedAgain, err := schemacontract.EncodeManifest(manifest)
	require.NoError(t, err)
	require.Equal(t, string(encoded), string(encodedAgain))

	state2, _ := generateModels(t, dbPath)
	manifest2, err := state2.SchemaContractManifest()
	require.NoError(t, err)
	encoded2, err := schemacontract.EncodeManifest(manifest2)
	require.NoError(t, err)
	require.Equal(t, string(encoded), string(encoded2))

	// The manifest must describe the view as read-only and preserve the
	// generated-column metadata.
	view := findTable(t, manifest, "", "pilot_names")
	require.True(t, view.IsView)
	require.False(t, view.ViewCapabilities.CanInsert)
	genDemo := findTable(t, manifest, "", "gen_demo")
	var doubled *schemacontract.ColumnContract
	for i := range genDemo.Columns {
		if genDemo.Columns[i].Name == "doubled" {
			doubled = &genDemo.Columns[i]
		}
	}
	require.NotNil(t, doubled)
	require.True(t, doubled.AutoGenerated)

	// Cross-check the real generated surface: tables get Insert, views do not.
	pilotsSrc, err := os.ReadFile(filepath.Join(out, "pilots.go"))
	require.NoError(t, err)
	require.Contains(t, string(pilotsSrc), "func (o *Pilot) Insert(")
	viewSrc, err := os.ReadFile(filepath.Join(out, "pilot_names.go"))
	require.NoError(t, err)
	require.NotContains(t, string(viewSrc), "func (o *PilotName) Insert(")
	// Default-based insert column sets are generated for tables.
	require.Contains(t, string(pilotsSrc), "pilotColumnsWithoutDefault")

	// No diff against the unchanged database.
	driver := drivers.GetDriver("sqlite3")
	report, err := schemacontract.CheckSchemaCompatibility(schemacontract.CheckOptions{
		Manifest: manifest,
		Driver:   driver,
		DriverConfig: drivers.Config{
			"dbname": dbPath,
			"pass":   "do-not-leak",
		},
	})
	require.NoError(t, err)
	require.True(t, report.ReadCompatible)
	require.True(t, report.WriteCompatible)
	require.Empty(t, report.Differences)
}

// TestSQLiteCompatibilityScenarios verifies the required classification
// scenarios against real sqlite databases.
func TestSQLiteCompatibilityScenarios(t *testing.T) {
	baselinePath := newSQLiteDB(t, baselineSQLiteDDL)
	state, _ := generateModels(t, baselinePath)
	manifest, err := state.SchemaContractManifest()
	require.NoError(t, err)
	driver := drivers.GetDriver("sqlite3")

	check := func(t *testing.T, path string) *schemacontract.Report {
		t.Helper()
		report, err := schemacontract.CheckSchemaCompatibility(schemacontract.CheckOptions{
			Manifest:     manifest,
			Driver:       driver,
			DriverConfig: drivers.Config{"dbname": path},
		})
		require.NoError(t, err)
		return report
	}

	t.Run("new safe nullable column", func(t *testing.T) {
		path := newSQLiteDB(t, baselineSQLiteDDL+`ALTER TABLE pilots ADD COLUMN nickname TEXT;`)
		report := check(t, path)
		diff := findDiff(t, report, "nickname", schemacontract.KindExtraUnusedColumn)
		require.NotNil(t, diff)
		require.True(t, report.ReadCompatible)
		require.True(t, report.WriteCompatible)
	})

	t.Run("new safe column with default", func(t *testing.T) {
		path := newSQLiteDB(t, baselineSQLiteDDL+`ALTER TABLE pilots ADD COLUMN tier INTEGER NOT NULL DEFAULT 0;`)
		report := check(t, path)
		require.NotNil(t, findDiff(t, report, "tier", schemacontract.KindExtraUnusedColumn))
		require.True(t, report.WriteCompatible)
	})

	t.Run("new required column breaks generated insert", func(t *testing.T) {
		path := newSQLiteDB(t, baselineSQLiteDDL+`ALTER TABLE pilots ADD COLUMN mandatory TEXT NOT NULL;`)
		report := check(t, path)
		diff := findDiff(t, report, "mandatory", schemacontract.KindRequiredColumnAdded)
		require.NotNil(t, diff)
		require.Equal(t, schemacontract.ImpactBreaks, diff.WriteImpact)
		require.Equal(t, schemacontract.ImpactSafe, diff.ReadImpact)
		require.False(t, report.WriteCompatible)
		require.True(t, report.ReadCompatible)
	})

	t.Run("type narrowing", func(t *testing.T) {
		ddl := strings.Replace(baselineSQLiteDDL, "age BIGINT", "age SMALLINT", 1)
		path := newSQLiteDB(t, ddl)
		report := check(t, path)
		diff := findDiff(t, report, "age", schemacontract.KindColumnTypeNarrowed)
		require.NotNil(t, diff)
		require.Equal(t, schemacontract.ImpactRisk, diff.WriteImpact)
		require.Equal(t, "BIGINT", diff.Evidence.Expected)
		require.Equal(t, "SMALLINT", diff.Evidence.Actual)
	})

	t.Run("custom type is unknown not compatible", func(t *testing.T) {
		// The modeled column starts as a known TEXT type; drifting it to a
		// custom application type must surface as unknown, never compatible.
		ddl := strings.Replace(baselineSQLiteDDL, "age BIGINT", "age PURPLE_TYPE", 1)
		path := newSQLiteDB(t, ddl)
		report := check(t, path)
		diff := findDiff(t, report, "age", schemacontract.KindColumnTypeUnknown)
		require.NotNil(t, diff)
		require.Equal(t, schemacontract.SeverityUnknown, diff.Severity)
		require.True(t, report.HasUnknowns)
		require.False(t, report.WriteCompatible)
	})

	t.Run("dropped column breaks select and insert", func(t *testing.T) {
		ddl := strings.Replace(baselineSQLiteDDL, "name TEXT NOT NULL,\n    age BIGINT", "name TEXT NOT NULL", 1)
		path := newSQLiteDB(t, ddl)
		report := check(t, path)
		diff := findDiff(t, report, "age", schemacontract.KindMissingColumn)
		require.NotNil(t, diff)
		require.Equal(t, schemacontract.ImpactBreaks, diff.ReadImpact)
		require.Equal(t, schemacontract.ImpactBreaks, diff.WriteImpact)
	})

	t.Run("view stays read-only", func(t *testing.T) {
		// sqlite views never report insert capability; an unchanged view must
		// not produce any view capability diff.
		path := newSQLiteDB(t, baselineSQLiteDDL)
		report := check(t, path)
		require.Nil(t, findDiff(t, report, "view_capabilities", schemacontract.KindViewInsertCapability))
	})

	t.Run("missing table", func(t *testing.T) {
		ddl := strings.Split(baselineSQLiteDDL, "CREATE TABLE jets")[0]
		path := newSQLiteDB(t, ddl)
		report := check(t, path)
		diff := findDiff(t, report, "tables[jets]", schemacontract.KindMissingTable)
		require.NotNil(t, diff)
		require.Equal(t, schemacontract.ImpactBreaks, diff.ReadImpact)
	})
}

// TestSQLiteCheckCancelAndFailure makes sure cancellation prevents
// introspection and driver failures surface without a report.
func TestSQLiteCheckCancelAndFailure(t *testing.T) {
	baselinePath := newSQLiteDB(t, baselineSQLiteDDL)
	state, _ := generateModels(t, baselinePath)
	manifest, err := state.SchemaContractManifest()
	require.NoError(t, err)
	driver := drivers.GetDriver("sqlite3")

	t.Run("cancelled context", func(t *testing.T) {
		ctx, cancel := context.WithCancel(context.Background())
		cancel()
		_, err := schemacontract.CheckSchemaCompatibility(schemacontract.CheckOptions{
			Context:      ctx,
			Manifest:     manifest,
			Driver:       driver,
			DriverConfig: drivers.Config{"dbname": baselinePath},
		})
		require.ErrorIs(t, err, context.Canceled)
	})

	t.Run("introspection failure", func(t *testing.T) {
		// sqlite opens lazily; a nonexistent directory fails the read-only
		// introspection queries inside Assemble.
		_, err := schemacontract.CheckSchemaCompatibility(schemacontract.CheckOptions{
			Manifest:     manifest,
			Driver:       driver,
			DriverConfig: drivers.Config{"dbname": filepath.Join(t.TempDir(), "missing", "nope.db")},
		})
		require.Error(t, err)
		require.Contains(t, err.Error(), "introspection failed")
	})
}

// TestSQLiteManifestRedaction proves credentials never reach the artifact.
func TestSQLiteManifestRedaction(t *testing.T) {
	dbPath := newSQLiteDB(t, baselineSQLiteDDL)

	m, err := schemacontract.Export(schemacontract.ExportOptions{
		DriverName: "sqlite3",
		Tables: []drivers.Table{{
			Name: "t",
			Columns: []drivers.Column{
				{Name: "id", DBType: "INTEGER", Type: "int64", Nullable: false},
			},
			PKey: &drivers.PrimaryKey{Columns: []string{"id"}},
		}},
		DriverConfig: drivers.Config{
			"dbname": dbPath,
			"pass":   "topsecret",
			"dsn":    "file:db?password=topsecret",
		},
	})
	require.NoError(t, err)
	raw, err := schemacontract.EncodeManifest(m)
	require.NoError(t, err)
	require.NotContains(t, string(raw), "topsecret")
	require.Contains(t, string(raw), schemacontract.RedactedValue)
}
