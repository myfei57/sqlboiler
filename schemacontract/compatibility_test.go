func TestCheckLoadsRulesOverDriverProtocol(t *testing.T) {
	// Manifest claims an unregistered driver, so the registry cannot satisfy
	// the lookup; the protocol fallback must provide the explicit rules.
	m := baselineManifest(t)
	m.DriverName = "protocol-driver"

	live := baselineTables()
	score := liveColumn(liveTable(live, "", "users"), "score")
	score.DBType = "SMALLINT" // contract BIGINT rank 4 -> live rank 2

	set := &drivers.TypeRuleSet{
		Driver: "protocol-driver",
		Families: map[string]drivers.TypeFamilyRule{
			"SMALLINT":  {Family: "integer", Rank: 2},
			"BIGINT":    {Family: "integer", Rank: 4},
			"INT":       {Family: "integer", Rank: 3},
			"VARCHAR":   {Family: "text", Rank: 1},
			"TEXT":      {Family: "text", Rank: 1},
			"TIMESTAMP": {Family: "time", Rank: 1},
		},
	}
	drv := &protocolDriver{
		fakeDriver: fakeDriver{info: &drivers.DBInfo{Tables: live}},
		ruleSet:    set,
	}
	report, err := CheckSchemaCompatibility(CheckOptions{Manifest: m, Driver: drv})
	require.NoError(t, err)
	require.False(t, report.HasUnknowns)
	require.NotNil(t, findDifference(t, report, "score", KindColumnTypeNarrowed))

	t.Run("provider error falls back to unknown", func(t *testing.T) {
		drv.ruleErr = errors.New("protocol unavailable")
		report, err := CheckSchemaCompatibility(CheckOptions{Manifest: m, Driver: drv})
		require.NoError(t, err)
		require.True(t, report.HasUnknowns)
	})

	t.Run("rule set for another driver is ignored", func(t *testing.T) {
		drv.ruleErr = nil
		drv.ruleSet.Driver = "different-driver"
		report, err := CheckSchemaCompatibility(CheckOptions{Manifest: m, Driver: drv})
		require.NoError(t, err)
		require.True(t, report.HasUnknowns)
	})
}

