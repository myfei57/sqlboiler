func TestCheckTypeNarrowingAndWidening(t *testing.T) {
	m := baselineManifest(t)

	t.Run("narrowed", func(t *testing.T) {
		live := baselineTables()
		score := liveColumn(liveTable(live, "", "users"), "score")
		score.DBType = "SMALLINT" // contract BIGINT rank 4 -> live rank 2

		report, _ := checkReport(t, m, live)
		diff := findDifference(t, report, "score", KindColumnTypeNarrowed)
		require.NotNil(t, diff)
		require.Equal(t, ImpactSafe, diff.ReadImpact)
		require.Equal(t, ImpactRisk, diff.WriteImpact)
		require.Equal(t, "BIGINT", diff.Evidence.Expected)
		require.Equal(t, "SMALLINT", diff.Evidence.Actual)
		require.False(t, report.WriteCompatible)
		require.True(t, report.ReadCompatible)
	})

	t.Run("widened", func(t *testing.T) {
		// Widen an integer column through a dedicated single-table manifest.
		manifest, err := Export(ExportOptions{
			DriverName: fixtureDriverName,
			Tables: []drivers.Table{{
				Name: "narrow",
				Columns: []drivers.Column{
					{Name: "id", DBType: "INT", Type: "int32", Nullable: false},
				},
				PKey: &drivers.PrimaryKey{Columns: []string{"id"}},
			}},
		})
		require.NoError(t, err)

		liveTables := []drivers.Table{{
			Name: "narrow",
			Columns: []drivers.Column{
				{Name: "id", DBType: "BIGINT", Type: "int64", Nullable: false},
			},
			PKey: &drivers.PrimaryKey{Columns: []string{"id"}},
		}}
		report, _ := checkReport(t, manifest, liveTables)
		diff := findDifference(t, report, "id", KindColumnTypeWidened)
		require.NotNil(t, diff)
		require.Equal(t, ImpactRisk, diff.ReadImpact)
		require.Equal(t, ImpactSafe, diff.WriteImpact)
		require.False(t, report.ReadCompatible)
		require.True(t, report.WriteCompatible)
	})

	t.Run("incompatible families", func(t *testing.T) {
		live := baselineTables()
		score := liveColumn(liveTable(live, "", "users"), "score")
		score.DBType = "VARCHAR"

		report, _ := checkReport(t, m, live)
		diff := findDifference(t, report, "score", KindColumnTypeIncompatible)
		require.NotNil(t, diff)
		require.Equal(t, ImpactBreaks, diff.ReadImpact)
		require.Equal(t, ImpactBreaks, diff.WriteImpact)
	})
}

