func checkReport(t *testing.T, m *Manifest, live []drivers.Table) (*Report, *fakeDriver) {
	t.Helper()
	drv := &fakeDriver{info: &drivers.DBInfo{Tables: live, Dialect: m.Dialect, Schema: m.Schema}}
	report, err := CheckSchemaCompatibility(CheckOptions{Manifest: m, Driver: drv})
	require.NoError(t, err)
	return report, drv
}

func liveTable(tables []drivers.Table, schema, name string) *drivers.Table {
	for i := range tables {
		if tables[i].SchemaName == schema && tables[i].Name == name {
			return &tables[i]
		}
	}
	return nil
}

func liveColumn(t *drivers.Table, name string) *drivers.Column {
	for i := range t.Columns {
		if t.Columns[i].Name == name {
			return &t.Columns[i]
		}
	}
	return nil
}

