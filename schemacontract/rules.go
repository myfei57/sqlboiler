package schemacontract

import (
	"sort"
	"strings"
	"sync"

	"github.com/aarondl/sqlboiler/v4/drivers"
)

// TypeVerdict is the structural result of comparing two column types. It is
// deliberately more expressive than a bool or a type-string equality check:
// numeric width changes have different read/write consequences.
type TypeVerdict string

const (
	// VerdictCompatible means the live type family and width match the
	// generation-time contract.
	VerdictCompatible TypeVerdict = "compatible"
	// VerdictWidened means the live type accepts a wider range of values
	// (e.g. contract INT32, live INT64). Reads may overflow the generated Go
	// type, writes generated by the model remain valid.
	VerdictWidened TypeVerdict = "widened"
	// VerdictNarrowed means the live type accepts a narrower range of values
	// (e.g. contract INT64, live INT16). Reads stay valid, writes may be
	// rejected or truncated.
	VerdictNarrowed TypeVerdict = "narrowed"
	// VerdictIncompatible means the type families differ (e.g. integer versus
	// text) and no safe automatic comparison exists.
	VerdictIncompatible TypeVerdict = "incompatible"
	// VerdictUnknown means the driver has no explicit rule for this type
	// (unknown domain, custom DB type, unregistered driver). It must never be
	// silently treated as compatible.
	VerdictUnknown TypeVerdict = "unknown"
)

// TypeRules encapsulates the explicit, driver-specific column type
// compatibility rules. Drivers register an implementation at init time (see
// RegisterTypeRules). The check never guesses: an implementation that does not
// know how to compare two columns must return VerdictUnknown.
type TypeRules interface {
	// DriverName is the drivers registration name the rules apply to, for
	// example "sqlite3".
	DriverName() string
	// CheckColumnType compares the generation-time column (expected, coming
	// from the manifest) with the live introspected column (actual).
	CheckColumnType(expected, actual drivers.Column) TypeVerdict
}

var (
	typeRulesMu sync.RWMutex
	typeRules   = map[string]TypeRules{}
)

// RegisterTypeRules installs type rules for a driver. It panics on duplicate
// registration, mirroring drivers.RegisterFromInit, so driver packages are
// safe to side-effect import.
func RegisterTypeRules(rules TypeRules) {
	if rules == nil {
		panic("schemacontract: cannot register nil type rules")
	}
	name := rules.DriverName()
	if name == "" {
		panic("schemacontract: type rules must report a driver name")
	}

	typeRulesMu.Lock()
	defer typeRulesMu.Unlock()
	if _, ok := typeRules[name]; ok {
		panic("schemacontract: type rules already registered for driver " + name)
	}
	typeRules[name] = rules
}

// TypeRulesFor returns the registered rules for a driver name.
func TypeRulesFor(driverName string) (TypeRules, bool) {
	typeRulesMu.RLock()
	defer typeRulesMu.RUnlock()
	r, ok := typeRules[driverName]
	return r, ok
}

// registeredTypeRuleNames is used by tests and diagnostics.
func registeredTypeRuleNames() []string {
	typeRulesMu.RLock()
	defer typeRulesMu.RUnlock()
	names := make([]string, 0, len(typeRules))
	for name := range typeRules {
		names = append(names, name)
	}
	sort.Strings(names)
	return names
}

// baseDBType strips parenthesised size/precision declarations and normalizes
// case, so "VARCHAR(1000)" and "varchar" compare on their family name. Width
// information that lives inside the parentheses is intentionally ignored here;
// driver rules implement width handling explicitly when needed.
func baseDBType(dbType string) string {
	dbType = strings.TrimSpace(dbType)
	if i := strings.IndexByte(dbType, '('); i >= 0 {
		dbType = dbType[:i]
	}
	return strings.ToUpper(strings.TrimSpace(dbType))
}

// TypeFamily describes a comparable family of database types and an ordered
// width rank where larger means wider.
type TypeFamily struct {
	Name  string
	Rank  int
	Known bool
}

// FamilyTable is a reusable driver rule implementation keyed by the uppercased
// base DB type. Drivers embed/fill it with their own type knowledge. Anything
// absent from the table, plus columns carrying a domain, yields
// VerdictUnknown instead of an implicit "compatible".
type FamilyTable struct {
	Driver string
	// Families maps uppercase base DB type (without parentheses) to family.
	Families map[string]TypeFamily
}

// CheckColumnType implements TypeRules using explicit family tables.
func (t FamilyTable) CheckColumnType(expected, actual drivers.Column) TypeVerdict {
	// Domains are named, user-defined constraints. A generic family table
	// cannot prove their compatibility, so demand explicit adaptation.
	if expected.DomainName != nil || actual.DomainName != nil {
		return VerdictUnknown
	}

	expectedFamily, ok := t.Families[baseDBType(expected.DBType)]
	if !ok || !expectedFamily.Known {
		return VerdictUnknown
	}
	actualFamily, ok := t.Families[baseDBType(actual.DBType)]
	if !ok || !actualFamily.Known {
		return VerdictUnknown
	}

	if expectedFamily.Name != actualFamily.Name {
		return VerdictIncompatible
	}
	switch {
	case actualFamily.Rank == expectedFamily.Rank:
		return VerdictCompatible
	case actualFamily.Rank > expectedFamily.Rank:
		return VerdictWidened
	default:
		return VerdictNarrowed
	}
}

// DriverName implements TypeRules.
func (t FamilyTable) DriverName() string {
	return t.Driver
}

// TypeRulesFromDriverSet adapts the serializable drivers.TypeRuleSet (which
// binary drivers expose over the driver protocol) to the in-process TypeRules
// interface.
func TypeRulesFromDriverSet(set *drivers.TypeRuleSet) TypeRules {
	if set == nil {
		return nil
	}
	families := make(map[string]TypeFamily, len(set.Families))
	for dbType, rule := range set.Families {
		families[dbType] = TypeFamily{Name: rule.Family, Rank: rule.Rank, Known: true}
	}
	return FamilyTable{Driver: set.Driver, Families: families}
}
