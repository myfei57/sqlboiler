// fixtureDriverName is a driver name that only exists in these tests. Its
// family rules are registered in TestMain so registry state stays deterministic.
const fixtureDriverName = "fixture-driver"

// fakeDriver serves canned introspection results without touching a database
// or any global connection state.
type fakeDriver struct {
	info      *drivers.DBInfo
	err       error
	assembles int
	lastCfg   drivers.Config
}

func (f *fakeDriver) Assemble(config drivers.Config) (*drivers.DBInfo, error) {
	f.assembles++
	f.lastCfg = config
	if f.err != nil {
		return nil, f.err
	}
	return f.info, nil
}

func (f *fakeDriver) Templates() (map[string]string, error) { return nil, nil }

func (f *fakeDriver) Imports() (importers.Collection, error) {
	return importers.Collection{}, nil
}

// protocolDriver wraps fakeDriver and provides type rules over the binary
// driver protocol surface (drivers.TypeRuleProvider).
type protocolDriver struct {
	fakeDriver
	ruleSet *drivers.TypeRuleSet
	ruleErr error
}

func (p *protocolDriver) TypeRules() (*drivers.TypeRuleSet, error) {
	return p.ruleSet, p.ruleErr
}

func strptr(s string) *string { return &s }

// baselineTables is the generation-time metadata used by most tests. It
// contains a composite-PK table with a generated column, a nullable column,
// default expressions, a foreign key/relationship, a read-only view and
// same-name tables in different schemas.
func baselineTables() []drivers.Table {
	users := drivers.Table{
		Name: "users",
		Columns: []drivers.Column{
			{Name: "id", Type: "int64", DBType: "BIGINT", Nullable: false},
			{Name: "tenant_id", Type: "int64", DBType: "BIGINT", Nullable: false},
			{Name: "name", Type: "string", DBType: "VARCHAR", FullDBType: "VARCHAR(50)", Nullable: false},
			{Name: "nickname", Type: "null.String", DBType: "VARCHAR", Nullable: true, Default: "NULL"},
			{Name: "score", Type: "null.Int64", DBType: "BIGINT", Nullable: true, Default: "NULL"},
			{Name: "created_at", Type: "null.Time", DBType: "TIMESTAMP", Nullable: true, Default: "current_timestamp"},
			{Name: "label", Type: "string", DBType: "TEXT", Nullable: false, AutoGenerated: true, Default: "auto_generated"},
		},
		PKey: &drivers.PrimaryKey{Name: "users_pkey", Columns: []string{"tenant_id", "id"}},
		FKeys: []drivers.ForeignKey{
			{
				Name: "users_tenant_fk", Table: "users", Column: "tenant_id", Nullable: false, Unique: false,
				ForeignTable: "accounts", ForeignColumn: "id", ForeignColumnNullable: false, ForeignColumnUnique: true,
			},
		},
		ToOneRelationships: []drivers.ToOneRelationship{
			{
				Name: "users_tenant_fk", Table: "users", Column: "id",
				ForeignTable: "accounts", ForeignColumn: "tenant_id",
				ForeignColumnNullable: false, ForeignColumnUnique: true,
			},
		},
	}

	accounts := drivers.Table{
		Name: "accounts",
		Columns: []drivers.Column{
			{Name: "id", Type: "int64", DBType: "BIGINT", Nullable: false},
			{Name: "name", Type: "string", DBType: "VARCHAR", Nullable: false},
		},
		PKey: &drivers.PrimaryKey{Name: "accounts_pkey", Columns: []string{"id"}},
	}

	view := drivers.Table{
		Name:   "user_view",
		IsView: true,
		ViewCapabilities: drivers.ViewCapabilities{
			CanInsert: false,
			CanUpsert: false,
		},
		Columns: []drivers.Column{
			{Name: "id", Type: "int64", DBType: "BIGINT", Nullable: false},
			{Name: "name", Type: "null.String", DBType: "VARCHAR", Nullable: true},
		},
	}

	// Same table name as users but inside schema s1: must stay independent.
	scopedUsersS1 := drivers.Table{
		SchemaName: "s1",
		Name:       "users",
		Columns: []drivers.Column{
			{Name: "id", Type: "int64", DBType: "BIGINT", Nullable: false},
			{Name: "scope", Type: "string", DBType: "VARCHAR", Nullable: false},
		},
		PKey: &drivers.PrimaryKey{Columns: []string{"id"}},
	}
	scopedUsersS2 := drivers.Table{
		SchemaName: "s2",
		Name:       "users",
		Columns: []drivers.Column{
			{Name: "id", Type: "int64", DBType: "BIGINT", Nullable: false},
			{Name: "scope", Type: "string", DBType: "VARCHAR", Nullable: false},
		},
		PKey: &drivers.PrimaryKey{Columns: []string{"id"}},
	}

	return []drivers.Table{users, accounts, view, scopedUsersS1, scopedUsersS2}
}

func baselineDBInfo() *drivers.DBInfo {
	return &drivers.DBInfo{
		Schema:  "",
		Dialect: drivers.Dialect{LQ: '"', RQ: '"', UseDefaultKeyword: true},
		Tables:  baselineTables(),
	}
}

// baselineManifest exports a manifest from the baseline tables.
func baselineManifest(t *testing.T) *Manifest {
	t.Helper()
	m, err := Export(ExportOptions{
		DriverName:       fixtureDriverName,
		GeneratorName:    "sqlboiler",
		GeneratorVersion: "test",
		Tables:           baselineTables(),
		PkgName:          "models",
		Settings:         map[string]any{"no_tests": true},
		DriverConfig: drivers.Config{
			"dbname": "app",
			"pass":   "super-secret",
			"host":   "localhost",
			"dsn":    "user:hunter2@tcp(db:3306)/app",
		},
		Aliases: map[string]any{
			"tables": map[string]any{
				"users": map[string]any{"up_singular": "User"},
			},
		},
	})
	if err != nil {
		t.Fatalf("export baseline manifest: %v", err)
	}
	return m
}

// findTableContract returns the manifest table for a schema/name pair.
func findTableContract(t *testing.T, m *Manifest, schema, name string) *TableContract {
	t.Helper()
	for i := range m.Tables {
		if m.Tables[i].SchemaName == schema && m.Tables[i].Name == name {
			return &m.Tables[i]
		}
	}
	t.Fatalf("table %s.%s not found in manifest", schema, name)
	return nil
}

// findDifference returns the first difference whose kind matches and whose
// schema path contains pathPart (empty pathPart matches any path).
func findDifference(t *testing.T, report *Report, pathPart, kind string) *Difference {
	t.Helper()
	for i := range report.Differences {
		d := &report.Differences[i]
		if d.Kind == kind && (pathPart == "" || strings.Contains(d.Path, pathPart)) {
			return d
		}
	}
	return nil
}
