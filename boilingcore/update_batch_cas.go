package boilingcore

import (
	"github.com/friendsofgo/errors"

	"github.com/aarondl/sqlboiler/v4/drivers"
)

// integerGoTypes is the closed set of non-nullable Go integer types a
// version column is allowed to use. Nullable "null.Int*" wrappers are
// deliberately excluded because the version column must be non-null.
var integerGoTypes = map[string]struct{}{
	"int":     {},
	"int8":    {},
	"int16":   {},
	"int32":   {},
	"int64":   {},
	"uint":    {},
	"uint8":   {},
	"uint16":  {},
	"uint32":  {},
	"uint64":  {},
	"uintptr": {},
}

// IsIntegerGoType reports whether typ is one of the non-nullable Go integer
// types accepted for an UpdateBatchCAS version column.
func IsIntegerGoType(typ string) bool {
	_, ok := integerGoTypes[typ]
	return ok
}

// normalizeUpdateBatchCAS fills budget defaults and validates the declared
// version columns against the assembled table metadata. It fails generation
// fast instead of emitting code that could not enforce the CAS contract.
func normalizeUpdateBatchCAS(cfg *UpdateBatchCASConfig, tables []drivers.Table) error {
	if !cfg.Enabled() {
		return nil
	}

	normalized, err := cfg.Normalized()
	if err != nil {
		return err
	}
	*cfg = normalized

	for _, table := range tables {
		if table.IsView || table.IsJoinTable {
			continue
		}

		versionColumnName, ok := cfg.VersionColumnFor(table.Name)
		if !ok {
			continue
		}

		versionColumn, err := findColumn(table, versionColumnName)
		if err != nil {
			return errors.Wrapf(err, "update_batch_cas: table %q", table.Name)
		}

		if versionColumn.Nullable {
			return errors.Errorf(
				"update_batch_cas: version column %q of table %q must be declared NOT NULL",
				versionColumnName, table.Name,
			)
		}

		if !IsIntegerGoType(versionColumn.Type) {
			return errors.Errorf(
				"update_batch_cas: version column %q of table %q must use a non-nullable integer Go type, got %q",
				versionColumnName, table.Name, versionColumn.Type,
			)
		}

		if table.PKey != nil {
			for _, pkColumn := range table.PKey.Columns {
				if pkColumn == versionColumnName {
					return errors.Errorf(
						"update_batch_cas: version column %q of table %q must not be part of the primary key",
						versionColumnName, table.Name,
					)
				}
			}
		}

		if versionColumn.AutoGenerated {
			return errors.Errorf(
				"update_batch_cas: version column %q of table %q must not be auto-generated",
				versionColumnName, table.Name,
			)
		}
	}

	return nil
}

func findColumn(table drivers.Table, name string) (drivers.Column, error) {
	for _, column := range table.Columns {
		if column.Name == name {
			return column, nil
		}
	}
	return drivers.Column{}, errors.Errorf("declared version column %q does not exist", name)
}
