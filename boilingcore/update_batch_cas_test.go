func TestUpdateBatchCASConfig_Normalized(t *testing.T) {
	t.Parallel()

	cfg, err := (UpdateBatchCASConfig{}).Normalized()
	if err != nil {
		t.Fatalf("unexpected error: %v", err)
	}
	if cfg.MaxBatchSize != DefaultUpdateBatchCASMaxRows {
		t.Errorf("default max batch size: want %d got %d", DefaultUpdateBatchCASMaxRows, cfg.MaxBatchSize)
	}
	if cfg.MaxSQLArgs != DefaultUpdateBatchCASMaxSQLArgs {
		t.Errorf("default max sql args: want %d got %d", DefaultUpdateBatchCASMaxSQLArgs, cfg.MaxSQLArgs)
	}

	if _, err := (UpdateBatchCASConfig{MaxBatchSize: -1}).Normalized(); err == nil {
		t.Error("negative batch size must be rejected")
	}
	if _, err := (UpdateBatchCASConfig{MaxSQLArgs: 0, MaxBatchSize: 1}).Normalized(); err != nil {
		t.Errorf("zero sql args should fall back to default: %v", err)
	}
}

func TestUpdateBatchCASConfig_VersionColumnFor(t *testing.T) {
	t.Parallel()

	cfg := UpdateBatchCASConfig{
		VersionColumn:  "version",
		VersionColumns: map[string]string{"special": "rev"},
	}
	if !cfg.Enabled() {
		t.Fatal("config should be enabled")
	}
	if name, ok := cfg.VersionColumnFor("cas_items"); !ok || name != "version" {
		t.Errorf("global column: got %q/%v", name, ok)
	}
	if name, ok := cfg.VersionColumnFor("special"); !ok || name != "rev" {
		t.Errorf("per-table override: got %q/%v", name, ok)
	}

	var disabled UpdateBatchCASConfig
	if disabled.Enabled() {
		t.Error("zero config must be disabled")
	}
	if _, ok := disabled.VersionColumnFor("cas_items"); ok {
		t.Error("disabled config must not resolve a column")
	}
}

func TestNormalizeUpdateBatchCAS(t *testing.T) {
	t.Parallel()

	base := func() []drivers.Table {
		tables := casTables()
		return tables
	}

	t.Run("valid", func(t *testing.T) {
		cfg := UpdateBatchCASConfig{VersionColumn: "version"}
		if err := normalizeUpdateBatchCAS(&cfg, base()); err != nil {
			t.Fatalf("unexpected error: %v", err)
		}
		if cfg.MaxBatchSize != DefaultUpdateBatchCASMaxRows {
			t.Error("defaults must be applied during normalization")
		}
	})

	t.Run("missing column", func(t *testing.T) {
		cfg := UpdateBatchCASConfig{VersionColumn: "nope"}
		if err := normalizeUpdateBatchCAS(&cfg, base()); err == nil {
			t.Fatal("missing version column must fail generation")
		}
	})

	t.Run("nullable version", func(t *testing.T) {
		tables := base()
		tables[0].Columns[4].Nullable = true
		tables[0].Columns[4].Type = "null.Int64"
		cfg := UpdateBatchCASConfig{VersionColumn: "version"}
		if err := normalizeUpdateBatchCAS(&cfg, tables); err == nil {
			t.Fatal("nullable version column must be rejected")
		}
	})

	t.Run("non integer version", func(t *testing.T) {
		tables := base()
		tables[0].Columns[4].Type = "string"
		cfg := UpdateBatchCASConfig{VersionColumn: "version"}
		if err := normalizeUpdateBatchCAS(&cfg, tables); err == nil {
			t.Fatal("non-integer version column must be rejected")
		}
	})

	t.Run("version in primary key", func(t *testing.T) {
		tables := base()
		tables[0].PKey = &drivers.PrimaryKey{Columns: []string{"tenant_id", "item_id", "version"}}
		cfg := UpdateBatchCASConfig{VersionColumn: "version"}
		if err := normalizeUpdateBatchCAS(&cfg, tables); err == nil {
			t.Fatal("primary-key version column must be rejected")
		}
	})

	t.Run("auto generated version", func(t *testing.T) {
		tables := base()
		tables[0].Columns[4].AutoGenerated = true
		cfg := UpdateBatchCASConfig{VersionColumn: "version"}
		if err := normalizeUpdateBatchCAS(&cfg, tables); err == nil {
			t.Fatal("auto-generated version column must be rejected")
		}
	})

	t.Run("views and join tables ignored", func(t *testing.T) {
		tables := base()
		tables = append(tables,
			drivers.Table{Name: "cas_view", IsView: true},
			drivers.Table{Name: "cas_join", IsJoinTable: true, PKey: &drivers.PrimaryKey{Columns: []string{"a", "b"}}},
		)
		cfg := UpdateBatchCASConfig{VersionColumn: "version"}
		if err := normalizeUpdateBatchCAS(&cfg, tables); err != nil {
			t.Fatalf("views/join tables must be skipped: %v", err)
		}
	})

	t.Run("disabled is a no-op", func(t *testing.T) {
		cfg := UpdateBatchCASConfig{}
		if err := normalizeUpdateBatchCAS(&cfg, base()); err != nil {
			t.Fatalf("disabled config must not error: %v", err)
		}
	})
}

// casFakeDriver serves hand-built table metadata without a live database.
type casFakeDriver struct {
	name    string
	dialect drivers.Dialect
	tables  []drivers.Table
}

func (d *casFakeDriver) Assemble(drivers.Config) (*drivers.DBInfo, error) {
	return &drivers.DBInfo{Dialect: d.dialect, Tables: d.tables}, nil
}
func (d *casFakeDriver) Templates() (map[string]string, error) { return nil, nil }
func (d *casFakeDriver) Imports() (importers.Collection, error) {
	col := importers.NewDefaultImports()
	col.BasedOnType = importers.Map{
		"null.String": {ThirdParty: importers.List{`"github.com/aarondl/null/v8"`}},
		"null.Int64":  {ThirdParty: importers.List{`"github.com/aarondl/null/v8"`}},
	}
	return col, nil
}

var registerCASDrivers sync.Once

func registerFakes() {
	registerCASDrivers.Do(func() {
		drivers.RegisterFromInit("sqlite3", &casFakeDriver{
			name:    "sqlite3",
			dialect: drivers.Dialect{LQ: '"', RQ: '"', UseDefaultKeyword: true},
			tables:  casTables(),
		})
		drivers.RegisterFromInit("psql", &casFakeDriver{
			name: "psql",
			dialect: drivers.Dialect{
				LQ: '"', RQ: '"', UseIndexPlaceholders: true, UseSchema: true, UseDefaultKeyword: true,
			},
			tables: casTables(),
		})
		drivers.RegisterFromInit("mysql", &casFakeDriver{
			name: "mysql",
			dialect: drivers.Dialect{
				LQ: '`', RQ: '`', UseLastInsertID: true,
			},
			tables: casTables(),
		})
	})
}

func TestUpdateBatchCASGeneration(t *testing.T) {
	if testing.Short() {
		t.SkipNow()
	}
	registerFakes()

	cases := []struct {
		name      string
		driver    string
		noContext bool
		noHooks   bool
		wantSQL   string
		wantUnsup bool
	}{
		{name: "sqlite3_context", driver: "sqlite3", wantSQL: "RETURNING"},
		{name: "psql_context", driver: "psql", wantSQL: "RETURNING"},
		{name: "sqlite3_no_context", driver: "sqlite3", noContext: true, wantSQL: "RETURNING"},
		{name: "sqlite3_no_hooks", driver: "sqlite3", noHooks: true, wantSQL: "RETURNING"},
		{name: "mysql_unsupported", driver: "mysql", wantUnsup: true},
	}

	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			out := generateCASModels(t, tc.driver, tc.noContext, tc.noHooks)

			generated, err := os.ReadFile(filepath.Join(out, "cas_items.go"))
			if err != nil {
				t.Fatalf("read generated file: %v", err)
			}
			text := string(generated)
			if !strings.Contains(text, "func UpdateBatchCASCasItem(") {
				t.Fatal("UpdateBatchCAS entry point was not generated")
			}
			if !tc.wantUnsup {
				if !strings.Contains(text, "boil.CheckVersionIncrement") {
					t.Fatal("pre-SQL version overflow check missing")
				}
			}
			if tc.noContext {
				if !strings.Contains(text, "boil.BeginBatchCAS(") {
					t.Fatal("non-context savepoint/tx guard missing")
				}
			} else if !tc.wantUnsup {
				if !strings.Contains(text, "boil.BeginContextBatchCAS(") {
					t.Fatal("context savepoint/tx guard missing")
				}
			}
			if tc.wantUnsup {
				if !strings.Contains(text, "UpdateBatchCASUnsupported") {
					t.Fatal("unsupported adapter must emit an explicit unsupported entry point")
				}
				if strings.Contains(text, "RETURNING") {
					t.Fatal("unsupported adapter must not emit RETURNING SQL")
				}
			} else if !strings.Contains(text, tc.wantSQL) {
				t.Fatalf("generated code must contain %q", tc.wantSQL)
			}

			compileGeneratedPackage(t, out)
		})
	}
}

func TestUpdateBatchCASDisabledGeneration(t *testing.T) {
	if testing.Short() {
		t.SkipNow()
	}
	registerFakes()

	out, err := os.MkdirTemp("", "boil_cas_disabled")
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = os.RemoveAll(out) })

	config := &Config{
		DriverName:     "sqlite3",
		PkgName:        "models",
		OutFolder:      out,
		NoTests:        true,
		DriverConfig:   drivers.Config{},
		Imports:        importers.NewDefaultImports(),
		UpdateBatchCAS: UpdateBatchCASConfig{},
	}
	state, err := New(config)
	if err != nil {
		t.Fatalf("New: %v", err)
	}
	if err := state.Run(); err != nil {
		t.Fatalf("Run: %v", err)
	}
	generated, err := os.ReadFile(filepath.Join(out, "cas_items.go"))
	if err != nil {
		t.Fatalf("read generated file: %v", err)
	}
	if strings.Contains(string(generated), "UpdateBatchCASCasItem") {
		t.Fatal("no UpdateBatchCAS code should be generated when disabled")
	}
	compileGeneratedPackage(t, out)
}

func generateCASModels(t *testing.T, driver string, noContext, noHooks bool) string {
	t.Helper()

	out, err := os.MkdirTemp("", "boil_cas_gen")
	if err != nil {
		t.Fatalf("tempdir: %v", err)
	}
	t.Cleanup(func() { _ = os.RemoveAll(out) })

	config := &Config{
		DriverName: driver,
		PkgName:    "models",
		OutFolder:  out,
		NoTests:    true,
		NoContext:  noContext,
		NoHooks:    noHooks,
		DriverConfig: drivers.Config{
			drivers.ConfigSchema: "main",
		},
		Imports: importers.NewDefaultImports(),
		UpdateBatchCAS: UpdateBatchCASConfig{
			VersionColumn: "version",
			MaxBatchSize:  3,
			MaxSQLArgs:    500,
		},
	}
	state, err := New(config)
	if err != nil {
		t.Fatalf("New: %v", err)
	}
	if err := state.Run(); err != nil {
		t.Fatalf("Run: %v", err)
	}
	return out
}

func compileGeneratedPackage(t *testing.T, out string) {
	t.Helper()

	buf := &bytes.Buffer{}
	goModPath, err := exec.Command("go", "env", "GOMOD").Output()
	if err != nil {
		t.Fatalf("go env GOMOD: %v", err)
	}

	run := func(name string, args ...string) {
		cmd := exec.Command(name, args...)
		cmd.Dir = out
		cmd.Stderr = buf
		cmd.Stdout = buf
		if err := cmd.Run(); err != nil {
			t.Fatalf("%s %s failed: %v\n%s", name, strings.Join(args, " "), err, buf.String())
		}
	}

	run("go", "mod", "init", "github.com/aarondl/sqlboiler-cas-test")
	run("go", "mod", "edit", fmt.Sprintf("-replace=github.com/aarondl/sqlboiler/v4=%s", filepath.Dir(string(goModPath))))
	run("go", "mod", "tidy")
	run("go", "test", "-c")
}
